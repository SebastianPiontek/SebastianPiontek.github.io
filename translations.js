/**
 * Sprach-Engine: Automatische Erkennung & Umschaltung
 */
const AuraLanguageEngine = {
  currentLang: "de",
  supportedLangs: ["de", "en", "fr", "es", "it", "pt", "nl", "pl", "tr", "ru", "hi", "ko"],

  init() {
    // 1. Gespeicherte Sprache aus localStorage prüfen
    const saved = localStorage.getItem("aura_preferred_lang");
    if (saved && this.supportedLangs.includes(saved)) {
      this.currentLang = saved;
    } else {
      // 2. Browsersprache automatisch erkennen
      const browserLang = (navigator.language || navigator.userLanguage || "de").slice(0, 2).toLowerCase();
      if (this.supportedLangs.includes(browserLang)) {
        this.currentLang = browserLang;
      } else {
        this.currentLang = "de"; // Standard-Rückfall
      }
    }

    // Seite übersetzen und Dropdown synchronisieren
    this.apply(this.currentLang);
    this.syncDropdown(this.currentLang);
  },

  setLanguage(lang) {
    if (!this.supportedLangs.includes(lang)) return;
    this.currentLang = lang;
    localStorage.setItem("aura_preferred_lang", lang);
    this.apply(lang);
    this.syncDropdown(lang);
  },

  apply(lang) {
    const dict = AURA_TRANSLATIONS[lang] || AURA_TRANSLATIONS.de;
    document.documentElement.lang = lang;

    // Alle Elemente mit data-i18n Attribut aktualisieren
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // Platzhalter oder Title-Attribute aktualisieren
    document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
      const raw = el.getAttribute("data-i18n-attr");
      const [attr, key] = raw.split(":");
      if (attr && key && dict[key]) {
        el.setAttribute(attr, dict[key]);
      }
    });
  },

  syncDropdown(lang) {
    const selector = document.getElementById("aura-lang-select");
    if (selector && selector.value !== lang) {
      selector.value = lang;
    }
  }
};

// Startet automatisch, sobald das Dokument geladen ist
if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", () => AuraLanguageEngine.init());
} else {
  AuraLanguageEngine.init();
}

// Global verfügbar machen für den Umschalter im Menü
window.AuraLanguageEngine = AuraLanguageEngine;
